import { PgClient } from "@effect/sql-pg";
import * as PgDrizzle from "drizzle-orm/effect-postgres";
import type { EffectPgQueryEffectHKT, EffectPgQueryResultHKT } from "drizzle-orm/effect-postgres";
import type { PgEffectDatabase } from "drizzle-orm/pg-core/effect";
import { migrate } from "drizzle-orm/effect-postgres/migrator";
import { fileURLToPath } from "node:url";
import { Config, Context, Duration, Effect, Layer, Schedule } from "effect";

// Postgres may still be starting when the server boots (a fresh container, a
// restart in an orchestrator), so the first round trip is retried for about
// half a minute before giving up.
const ClientLive = PgClient.layerFrom(
  Effect.gen(function* () {
    const url = yield* Config.Redacted("DATABASE_URL");
    const maxConnections = yield* Config.Int("DATABASE_POOL_MAX").pipe(Config.withDefault(10));
    const client = yield* PgClient.make({
      url,
      maxConnections,
      connectTimeout: Duration.seconds(5),
      applicationName: "crm-server",
    });
    yield* client`SELECT 1`.pipe(
      Effect.tapError((error) => Effect.logWarning("Waiting for Postgres", error.message)),
      Effect.retry({ schedule: Schedule.spaced("1 second"), times: 30 }),
    );
    return client;
  }),
);

// Generated by drizzle-kit from `schema.ts`; applied ids are tracked in
// `drizzle.__drizzle_migrations`. Never edit a migration that has shipped:
// change the schema and generate a new one.
const migrationsFolder = fileURLToPath(new URL("../../drizzle", import.meta.url));

const makeDb = Effect.gen(function* () {
  const db = yield* PgDrizzle.makeWithDefaults();
  yield* migrate(db, { migrationsFolder });
  return db;
}).pipe(Effect.orDie);

/**
 * What each slice's store functions take first: the database, or a transaction
 * opened with `db.transaction(tx => …)`, so one unit of work can span several
 * slices. Drizzle statements are Effects: `yield*` them.
 */
export type Database = PgEffectDatabase<EffectPgQueryEffectHKT, EffectPgQueryResultHKT>;

/** The database, on a migrated schema. HTTP groups take it once and pass it on. */
export class Db extends Context.Service<Db, Database>()("app/Db") {
  static readonly layer = Layer.effect(Db, makeDb).pipe(Layer.provide(ClientLive));
}
